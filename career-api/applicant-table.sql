CREATE TABLE IF NOT EXISTS `applicant` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `fullname` VARCHAR(150) NOT NULL,
  `dept` VARCHAR(150) NOT NULL,
  `position` VARCHAR(150) NOT NULL,
  `high_qualification` VARCHAR(100) NOT NULL,
  `social_cat` VARCHAR(50) NOT NULL,
  `current_institution` VARCHAR(200) DEFAULT NULL,
  `current_position` VARCHAR(150) DEFAULT NULL,
  `city` VARCHAR(100) DEFAULT NULL,
  `state` VARCHAR(100) DEFAULT NULL,
  `country` VARCHAR(100) NOT NULL,
  `mobile` VARCHAR(25) NOT NULL,
  `email` VARCHAR(190) NOT NULL,
  `dob` DATE NOT NULL,
  `teaching` VARCHAR(20) DEFAULT '0',
  `industry` VARCHAR(20) DEFAULT '0',
  `research` VARCHAR(20) DEFAULT '0',
  `current_salary_range` VARCHAR(100) DEFAULT NULL,
  `expected_salary_range` VARCHAR(100) NOT NULL,
  `notice_period` VARCHAR(100) DEFAULT NULL,
  `resume` VARCHAR(255) NOT NULL,
  `why_change` TEXT,
  `source` VARCHAR(100) DEFAULT NULL,
  `institute` VARCHAR(100) NOT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_applicant_email` (`email`),
  KEY `idx_applicant_created_at` (`created_at`),
  KEY `idx_applicant_position` (`position`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
